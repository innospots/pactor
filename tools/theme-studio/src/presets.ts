/**
 * 预置主题（spec: theme-studio / 预置主题选择与应用）。
 *
 * 每套主题是一种完整视觉风格（配色 + 圆角 + 阴影 + 背景底色的组合），
 * 并提供配套暗色令牌组（darkTokens）使暗色模式保持同一风格。
 * 只定义该风格需要覆盖的令牌子集；未覆盖的组件级令牌靠 styles.css
 * 默认 var() 回退自动跟随；背景/前景成对覆盖。取色部分参考中国传统色
 * （china_colors.md，如 珊瑚赫/青冥/碧山/柘黃），hex 直接作令牌值。
 * 主题按钮以 swatches 展示代表色板。
 */

export interface SkinPreset {
  /** 主题 key（选中态标识） */
  key: string;
  /** 主题名（列表展示） */
  name: string;
  /** 风格说明 */
  description: string;
  /** 色板缩略（主题按钮展示的代表色） */
  swatches: string[];
  /** 亮令牌子集覆盖（令牌名 → CSS 值） */
  tokens: Record<string, string>;
  /** 配套暗色令牌组（[data-pactor-theme='dark'] 覆盖块，保持同一风格） */
  darkTokens: Record<string, string>;
}

