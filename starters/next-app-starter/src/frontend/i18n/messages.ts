export const messages: Record<Locale, Record<MessageKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

/** 宿主文案翻译（{{name}} 插值；locale 未就绪时回退默认语言，再回退 key 本身） */
export function translate(
  locale: Locale | null | undefined,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const active = locale ?? "zh-CN";
  const template = messages[active][key] ?? messages["zh-CN"][key] ?? key;
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (raw, name: string) =>
    params[name] !== undefined ? String(params[name]) : raw,
  );
}

export type HostTranslate = (
  key: MessageKey,
  params?: Record<string, string | number>,
) => string;

/** 自定义组件共用的当前语言与翻译函数。 */
export function useHostI18n(): {
  locale: Locale;
  changeLocale: (next: string) => void;
  t: HostTranslate;
} {
  const { locale, changeLocale } = useLocale();
  const active = locale ?? "zh-CN";
  return {
    locale: active,
    changeLocale,
    t: (key, params) => translate(active, key, params),
  };
}
