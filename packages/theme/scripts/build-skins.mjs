#!/usr/bin/env node
/**
 * 生成自包含的皮肤 CSS：
 *   themes.json + src/skins/*.css  →  skins/<name>.css
 *
 * 薄皮肤首行 `@import './_base.css';` 会被原地内联；发布物不允许任何 @import。
 * `--check` 只比对不写盘，供 CI / release 前检查生成物是否已提交。
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(packageRoot, 'src', 'skins');
const outputDir = join(packageRoot, 'skins');
const checkOnly = process.argv.includes('--check');

function normalize(text) {
  return text.replace(/^﻿/, '').replace(/\r\n/g, '\n');
}

function fail(message) {
  throw new Error(`[build-skins] ${message}`);
}

function loadManifest() {
  const raw = JSON.parse(
    readFileSync(join(packageRoot, 'themes.json'), 'utf8'),
  );
  if (!raw || typeof raw !== 'object' || !Array.isArray(raw.themes)) {
    fail('themes.json must contain a themes array');
  }
  if (typeof raw.default !== 'string') {
    fail('themes.json must contain a default theme name');
  }
  return raw;
}

function validateManifest(manifest) {
  const names = new Set();
  for (const theme of manifest.themes) {
    if (
      !theme ||
      typeof theme.name !== 'string' ||
      !/^[a-z0-9-]+$/.test(theme.name)
    ) {
      fail(`invalid theme name: ${JSON.stringify(theme?.name)}`);
    }
    if (names.has(theme.name)) fail(`duplicate theme name: ${theme.name}`);
    names.add(theme.name);
    if (typeof theme.color !== 'string' || !/^#[0-9a-f]{6}$/i.test(theme.color)) {
      fail(`invalid color for ${theme.name}: ${JSON.stringify(theme.color)}`);
    }
    if (theme.kind !== 'tokens' && theme.kind !== 'full') {
      fail(`invalid kind for ${theme.name}: ${JSON.stringify(theme.kind)}`);
    }
  }
  if (!names.has(manifest.default)) {
    fail(`default theme "${manifest.default}" is not in themes.json`);
  }
  return names;
}

function validateSources(names) {
  if (!existsSync(sourceDir)) fail(`missing source directory: ${sourceDir}`);
  const sourceNames = readdirSync(sourceDir)
    .filter((file) => file.endsWith('.css') && file !== '_base.css')
    .map((file) => file.slice(0, -4));
  for (const name of names) {
    if (!sourceNames.includes(name)) {
      fail(`missing src/skins/${name}.css`);
    }
  }
  for (const name of sourceNames) {
    if (!names.has(name)) {
      fail(`orphan source src/skins/${name}.css (not in themes.json)`);
    }
  }
  const loaders = readFileSync(join(packageRoot, 'src', 'loaders.ts'), 'utf8');
  for (const name of names) {
    if (!loaders.includes(`'../skins/${name}.css'`)) {
      fail(`src/loaders.ts is missing the literal import for ${name}`);
    }
  }
}

function buildSkin(theme) {
  const base = normalize(readFileSync(join(sourceDir, '_base.css'), 'utf8'));
  const source = normalize(
    readFileSync(join(sourceDir, `${theme.name}.css`), 'utf8'),
  );
  const importPattern =
    /^\s*@import\s+(?:url\(\s*)?['"]\.\/_base\.css['"]\s*\)?\s*;\s*\n?/;
  let body = source;
  if (importPattern.test(body)) {
    body = body.replace(importPattern, '');
    body = `${base.trimEnd()}\n\n${body.replace(/^\n+/, '')}`;
  }
  const header = `/* Generated by @pactor-app/theme from src/skins/${theme.name}.css. Do not edit. */\n`;
  return `${header}${body.trimEnd()}\n`;
}

function withoutComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

function validateOutput(theme, css) {
  const name = theme.name;
  if (/@import\b/.test(css)) fail(`${name}.css still contains @import`);
  if (!/:root:not\(\[data-pactor-theme=['"]dark['"]\]\)/.test(css)) {
    fail(`${name}.css is missing the light selector`);
  }
  if (!/\[data-pactor-theme=['"]dark['"]\]/.test(css)) {
    fail(`${name}.css is missing the dark selector`);
  }
  if (!/color-scheme\s*:\s*light\b/.test(css)) {
    fail(`${name}.css is missing color-scheme: light`);
  }
  if (!/color-scheme\s*:\s*dark\b/.test(css)) {
    fail(`${name}.css is missing color-scheme: dark`);
  }
  if (!/--background\s*:/.test(css)) {
    fail(`${name}.css is missing --background`);
  }
  const declarations = withoutComments(css);
  if (/--pactor-control-[a-z0-9-]+\s*:/.test(declarations)) {
    fail(`${name}.css defines --pactor-control-* (density contract violation)`);
  }
  const colors = [...declarations.matchAll(/--theme-source\s*:\s*(#[0-9a-f]{6})\b/gi)]
    .map((match) => match[1].toLowerCase());
  if (colors.length === 0) {
    fail(`${name}.css is missing --theme-source`);
  }
  if (colors.some((color) => color !== theme.color.toLowerCase())) {
    fail(
      `${name}.css --theme-source (${colors.join(', ')}) does not match themes.json (${theme.color})`,
    );
  }
}

function main() {
  const manifest = loadManifest();
  const names = validateManifest(manifest);
  validateSources(names);

  if (!checkOnly) mkdirSync(outputDir, { recursive: true });

  const stale = [];
  for (const theme of manifest.themes) {
    const css = buildSkin(theme);
    if (buildSkin(theme) !== css) {
      fail(`non-deterministic output for ${theme.name}`);
    }
    validateOutput(theme, css);

    const outputPath = join(outputDir, `${theme.name}.css`);
    if (checkOnly) {
      const current = existsSync(outputPath)
        ? normalize(readFileSync(outputPath, 'utf8'))
        : null;
      if (current !== css) stale.push(theme.name);
    } else {
      writeFileSync(outputPath, css);
    }
  }

  if (existsSync(outputDir)) {
    const generated = readdirSync(outputDir)
      .filter((file) => file.endsWith('.css'))
      .map((file) => file.slice(0, -4));
    for (const name of generated) {
      if (!names.has(name)) {
        if (checkOnly) stale.push(`${name} (orphan)`);
        else fail(`orphan generated skins/${name}.css (not in themes.json)`);
      }
    }
  }

  if (checkOnly && stale.length > 0) {
    fail(`skins/ is stale; run "pnpm build:skins" and commit: ${stale.join(', ')}`);
  }

  const action = checkOnly ? 'verified' : 'generated';
  console.log(`[build-skins] ${action} ${manifest.themes.length} skins`);
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
